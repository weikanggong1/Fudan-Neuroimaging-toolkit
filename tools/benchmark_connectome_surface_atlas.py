"""Compare original UKB cortical atlas script with PyTorch on one real FreeSurfer subject."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
from time import perf_counter

import nibabel as nib
import numpy as np
import torch

from fnit.connectome.atlas_surface import surface_annotation_to_volume


def _sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--subject-dir", type=Path, required=True,
                        help="Official recon-all subject with mri/ribbon.mgz, surf/, label/")
    parser.add_argument("--original-script", type=Path, required=True,
                        help="Original UKB scripts/python/map_surface_label_to_volume.py")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--device", default="cuda:0")
    parser.add_argument("--dataset-label", default="real FreeSurfer subject")
    parser.add_argument("--subject-id", default="test")
    parser.add_argument("--instance", default="ses2mm")
    parser.add_argument("--reference-python", default=sys.executable,
                        help="Python with the original script dependencies (SciPy, pandas, nibabel)")
    args = parser.parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    inputs = [args.subject_dir / "mri/ribbon.mgz"]
    for hemi in ("lh", "rh"):
        inputs.extend(args.subject_dir / f"surf/{hemi}.{name}" for name in ("pial", "white"))
        inputs.append(args.subject_dir / f"label/{hemi}.aparc.annot")
    for path in inputs + [args.original_script]:
        if not path.exists():
            raise FileNotFoundError(path)
    # Reproduce the original script's required UKB subject/temporary directory
    # layout with symlinks; reference output is generated by the original file.
    root = args.output_dir / "upstream_layout"
    subject_parent = root / "subjects"
    subject_name = f"{args.subject_id}_{args.instance}"
    subject = subject_parent / subject_name
    subject.mkdir(parents=True, exist_ok=True)
    freesurfer_link = subject / "FreeSurfer"
    if not freesurfer_link.exists():
        freesurfer_link.symlink_to(args.subject_dir.resolve(), target_is_directory=True)
    atlas_dir = root / "data/temporary/subjects" / subject_name / "atlases"
    atlas_dir.mkdir(parents=True, exist_ok=True)
    for hemi in ("lh", "rh"):
        link = atlas_dir / f"{hemi}.native.aparc.annot"
        if not link.exists():
            link.symlink_to((args.subject_dir / f"label/{hemi}.aparc.annot").resolve())
    upstream_command = [args.reference_python, str(args.original_script.resolve()),
                        str(root), str(subject_parent), args.subject_id, args.instance, "aparc"]
    start = perf_counter()
    reference_run = subprocess.run(upstream_command, check=True, text=True,
                                   capture_output=True)
    original_seconds = perf_counter() - start
    reference_path = atlas_dir / "native.aparc.nii.gz"
    reference_image = nib.load(str(reference_path))
    reference = np.asarray(reference_image.dataobj).astype(np.int32)
    ribbon_image = nib.load(str(inputs[0]))
    ribbon = np.asarray(ribbon_image.dataobj).astype(np.int32)
    surfaces = {}
    annotations = {}
    for hemi in ("lh", "rh"):
        surfaces[hemi] = tuple(np.asarray(nib.freesurfer.read_geometry(
            str(args.subject_dir / f"surf/{hemi}.{name}"))[0], dtype=np.float64)
            for name in ("pial", "white"))
        annotations[hemi] = np.asarray(nib.freesurfer.read_annot(
            str(args.subject_dir / f"label/{hemi}.aparc.annot"))[0], dtype=np.int32)
    if args.device.startswith("cuda"):
        torch.cuda.reset_peak_memory_stats()
    start = perf_counter()
    candidate = surface_annotation_to_volume(
        torch.as_tensor(ribbon, device=args.device),
        torch.as_tensor(ribbon_image.header.get_vox2ras_tkr(), device=args.device),
        *[torch.as_tensor(value, device=args.device) for value in (
            surfaces["lh"][0], surfaces["lh"][1], annotations["lh"],
            surfaces["rh"][0], surfaces["rh"][1], annotations["rh"]
        )],
    )
    if args.device.startswith("cuda"):
        torch.cuda.synchronize(args.device)
    torch_seconds = perf_counter() - start
    peak_gib = (torch.cuda.max_memory_allocated() / 2**30
                if args.device.startswith("cuda") else None)
    candidate = candidate.cpu().numpy()
    mismatch = candidate != reference
    foreground_a, foreground_b = candidate > 0, reference > 0
    label_dice = {}
    for label in np.union1d(np.unique(candidate), np.unique(reference)):
        if label <= 0:
            continue
        a, b = candidate == label, reference == label
        label_dice[str(int(label))] = float(2 * (a & b).sum() / (a.sum() + b.sum()))
    candidate_path = args.output_dir / "pytorch_native.aparc.nii.gz"
    nib.save(nib.Nifti1Image(candidate, ribbon_image.header.get_vox2ras()),
             str(candidate_path))
    report = {
        "dataset": args.dataset_label,
        "source": "original UKB-connectomics map_surface_label_to_volume.py, native aparc labels",
        "input_sha256": {p.name: _sha256(p) for p in inputs},
        "source_sha256": {
            "original_script": _sha256(args.original_script),
            "pytorch_operator": _sha256(Path(__file__).parents[1] / "src/fnit/connectome/atlas_surface.py")
        },
        "shape": list(candidate.shape),
        "ribbon_cortex_voxels": {
            "lh": int((ribbon == 3).sum()), "rh": int((ribbon == 42).sum())
        },
        "reference_command": upstream_command,
        "reference_stdout": reference_run.stdout.strip(),
        "reference_seconds_full_process_io": original_seconds,
        "torch_seconds_compute_and_host_to_device": torch_seconds,
        "torch_cuda_peak_allocated_gib": peak_gib,
        "voxel_mismatch_count": int(mismatch.sum()),
        "voxel_mismatch_by_hemi": {
            "lh": int((mismatch & (ribbon == 3)).sum()),
            "rh": int((mismatch & (ribbon == 42)).sum())
        },
        "foreground_dice": float(2 * (foreground_a & foreground_b).sum() /
                                 (foreground_a.sum() + foreground_b.sum())),
        "label_dice_min": min(label_dice.values()),
        "n_labels": len(label_dice),
        "reference_affine_equals_ribbon_vox2ras": bool(np.allclose(
            reference_image.affine, ribbon_image.header.get_vox2ras(), atol=1e-6)),
        "candidate_equals_reference_affine": bool(np.allclose(
            nib.load(str(candidate_path)).affine, reference_image.affine, atol=1e-6)),
        "reference_output_sha256": _sha256(reference_path),
        "candidate_output_sha256": _sha256(candidate_path),
    }
    (args.output_dir / "surface_atlas.internal.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
